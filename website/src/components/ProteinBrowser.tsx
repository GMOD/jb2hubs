// react-msaview pulls in @jbrowse/core + MUI + mobx and renders to canvas, so it
// only runs client-side; lazy-loading keeps it off the first paint and out of
// the cartoon/genome path until there is an alignment to draw.
const MSAViewer = lazy(() =>
  import('react-msaview').then(m => ({ default: m.MSAViewer })),
)

// Precomputed panel + alignment for the example genes (generated by
// generateProteinExamples.ts), keyed by `${SYMBOL}:${refTaxId}`. Lets a chip
// click render the cartoon and the full alignment with no NCBI/EBI wait.
// The alignment half is optional: generateBroadPanel.ts writes the panel alone
// unless --align is passed, because a broad panel's EBI job is minutes and the
// domain cartoon needs phase 1 only. Declaring it required made typecheck bless
// a `cached.alignment.fasta` that the shipped file cannot satisfy.
interface CachedExample {
  panel: ProteinPanel
  alignment?: ProteinAlignment
}

// Optional precomputed cache: a load failure just means examples resolve live,
// so degrade to an empty map rather than surfacing an error.
function loadExampleCache(): Promise<Record<string, CachedExample>> {
  return loadJsonOnce<Record<string, CachedExample>>(
    '/proteinExamples.json',
  ).catch((): Record<string, CachedExample> => ({}))
}

const cacheKey = (symbol: string, ref: number) =>
  `${symbol.trim().toUpperCase()}:${ref}`

// client:only island, so window is available for the shareable ?gene=&ref= link.
function paramsFromUrl() {
  const p = new URLSearchParams(window.location.search)
  const ref = Number(p.get('ref'))
  return { gene: p.get('gene')?.trim() ?? '', ref: ref > 0 ? ref : 9606 }
}

function message(e: unknown) {
  return e instanceof Error ? e.message : String(e)
}

interface Resolved {
  structure: GeneStructure
  panel?: ProteinPanel
  panelError?: string
  // the precomputed alignment for an example gene, used to skip EBI
  precomputed?: ProteinAlignment
  // whether this gene has a row in the hosted 100-way alignment
  hundredWay: boolean
}

// Phase 1: the gene's own genome/AlphaFold structure and the ortholog domain
// panel, resolved together. Example genes take the panel side from the
// precomputed cache instantly; everything else resolves live.
//
// A failed panel is NOT fatal. The genome view and the AlphaFold structure come
// from the structure half alone, and they are worth having even when no ortholog
// set covers the gene — which is exactly the case on the species where ortholog
// coverage is thinnest.
async function resolveGene(
  sym: string,
  ref: number,
  onProgress: (s: string) => void,
): Promise<Resolved> {
  const cached = (await loadExampleCache())[cacheKey(sym, ref)]
  const panelPromise = cached
    ? Promise.resolve(cached.panel)
    : assembleProteinPanel(sym, ref, { onProgress })
  const [structure, panelOutcome] = await Promise.all([
    fetchGeneStructure(sym, ref),
    panelPromise.then(
      panel => ({ panel }),
      (e: unknown) => ({ panelError: message(e) }),
    ),
  ])
  return {
    structure,
    ...panelOutcome,
    precomputed: cached?.alignment,
    // keyed on NCBI's canonical spelling of the symbol, which is what the
    // hosted index uses — a typed "tp53" would otherwise miss
    hundredWay: await hasHundredWay(structure.symbol, ref),
  }
}

export default function ProteinBrowser() {
  // The submitted query, as opposed to what is currently in the boxes: it is the
  // SWR key, so it changes only on Explore/Enter/an example chip. Seeded from the
  // page url, which is what makes a shared ?gene=&ref= link resolve on mount —
  // this island is client:only, so window is readable during the first render.
  const [query, setQuery] = useState(paramsFromUrl)
  const [gene, setGene] = useState(query.gene)
  const [taxId, setTaxId] = useState(query.ref)
  const [status, setStatus] = useState('')
  const [helpOpen, setHelpOpen] = useState(false)

  const {
    data,
    error,
    isLoading: loading,
  } = useSWRImmutable(
    query.gene ? (['protein-gene', query.gene, query.ref] as const) : null,
    ([, sym, ref]) => resolveGene(sym, ref, setStatus),
    LIVE_QUERY,
  )

  const run = (rawQuery: string, ref: number) => {
    const sym = rawQuery.trim()
    if (sym) {
      setGene(sym)
      setTaxId(ref)
      setQuery({ gene: sym, ref })
      syncGeneUrl(sym, ref)
    }
  }

  // Symbols do not carry across organisms, so a species switch follows NCBI's
  // ortholog to the new species rather than re-running a symbol that means
  // nothing there. Nothing to follow (or no ortholog) just changes the species.
  const switchSpecies = (ref: number) => {
    setTaxId(ref)
    const geneId = data?.structure.geneId
    if (geneId && query.gene) {
      setStatus('Following the ortholog…')
      void fetchOrthologSymbol(geneId, ref).then(symbol => {
        setStatus('')
        if (symbol) {
          run(symbol, ref)
        }
      })
    }
  }

  const examples = examplesFor(taxId)

  return (
    <div>
      <div className="ui-form">
        <GeneCombobox
          value={gene}
          taxId={taxId}
          disabled={loading}
          onChange={setGene}
          onSubmit={symbol => {
            run(symbol, taxId)
          }}
        />
        <select
          className="ui-select"
          value={taxId}
          onChange={e => {
            switchSpecies(Number(e.target.value))
          }}
          disabled={loading}
          aria-label="Reference organism"
        >
          {COMMON_SPECIES.map(s => (
            <option
              key={s.taxId}
              value={s.taxId}
            >
              {s.label}
            </option>
          ))}
        </select>
        <button
          className="ui-btn"
          onClick={() => {
            run(gene, taxId)
          }}
          disabled={loading || !gene.trim()}
        >
          {loading ? 'Resolving…' : 'Explore'}
        </button>
        <HelpButton
          label="How the protein browser works"
          onClick={() => {
            setHelpOpen(true)
          }}
        />
      </div>

      <div className="msv-examples">
        <span>Examples:</span>
        {examples.map(ex => (
          <button
            key={ex.symbol}
            className="ui-chip-btn"
            title={ex.note}
            disabled={loading}
            onClick={() => {
              run(ex.symbol, taxId)
            }}
          >
            {ex.symbol}
          </button>
        ))}
      </div>

      {loading && <p className="ui-hint">{status || 'Resolving…'}</p>}
      <ErrorMessage
        error={error}
        className="ui-error"
      />

      {data && (
        // Remounted per query, which is what drops a previous gene's alignment
        // request back to the cartoon without an effect to reset it.
        <GeneResults
          key={`${query.gene}:${query.ref}`}
          {...data}
          taxId={query.ref}
          status={status}
          onProgress={setStatus}
        />
      )}

      {helpOpen && (
        <HelpDialog
          onClose={() => {
            setHelpOpen(false)
          }}
        />
      )}
    </div>
  )
}

// A gene-symbol box with suggestions. Deliberately free-text: Enter submits what
// was typed unless a suggestion is highlighted, so a symbol the type-ahead has
// not heard of (or has not answered for yet) still runs. The suggestions are a
// convenience; NCBI decides whether the gene exists.
function GeneCombobox({
  value,
  taxId,
  disabled,
  onChange,
  onSubmit,
}: {
  value: string
  taxId: number
  disabled: boolean
  onChange: (v: string) => void
  onSubmit: (v: string) => void
}) {
  const [hits, setHits] = useState<string[]>([])
  const [open, setOpen] = useState(false)
  const [highlighted, setHighlighted] = useState(-1)
  // what the user typed, as opposed to a symbol put in the box by a chip or a
  // species switch — only typing should fire a lookup
  const [typed, setTyped] = useState('')
  const boxRef = useRef<HTMLDivElement>(null)

  // Debounced and race-safe: the cleanup drops a slow earlier response so it
  // cannot land on top of a newer one.
  useEffect(() => {
    if (typed.trim().length < 2) {
      setHits([])
      return
    }
    let ignore = false
    const timer = setTimeout(() => {
      void searchGenes(typed.trim(), taxId).then(found => {
        // set even when empty, so a no-match query clears stale suggestions
        if (!ignore) {
          setHits(found)
          setHighlighted(-1)
        }
      })
    }, 220)
    return () => {
      ignore = true
      clearTimeout(timer)
    }
  }, [typed, taxId])

  useEffect(() => {
    function onDocMouseDown(e: MouseEvent) {
      if (boxRef.current && !boxRef.current.contains(e.target as Node)) {
        setOpen(false)
      }
    }
    document.addEventListener('mousedown', onDocMouseDown)
    return () => {
      document.removeEventListener('mousedown', onDocMouseDown)
    }
  }, [])

  const choose = (symbol: string) => {
    onChange(symbol)
    setTyped('')
    setOpen(false)
    onSubmit(symbol)
  }

  const showList = open && hits.length > 0 && !disabled

  return (
    <div
      className="msv-combobox"
      ref={boxRef}
    >
      <input
        className="ui-input"
        value={value}
        role="combobox"
        aria-expanded={showList}
        aria-controls="msv-gene-listbox"
        aria-autocomplete="list"
        autoComplete="off"
        placeholder="Gene symbol, e.g. TP53"
        disabled={disabled}
        onChange={e => {
          onChange(e.target.value)
          setTyped(e.target.value)
          setOpen(true)
        }}
        onFocus={() => {
          setOpen(true)
        }}
        onKeyDown={e => {
          if (e.key === 'ArrowDown' && showList) {
            e.preventDefault()
            setHighlighted(i => Math.min(i + 1, hits.length - 1))
          } else if (e.key === 'ArrowUp' && showList) {
            e.preventDefault()
            setHighlighted(i => Math.max(i - 1, -1))
          } else if (e.key === 'Enter') {
            e.preventDefault()
            const picked = showList ? hits[highlighted] : undefined
            choose(picked ?? value)
          } else if (e.key === 'Escape') {
            setOpen(false)
          }
        }}
      />
      {showList && (
        <ul
          className="msv-listbox"
          id="msv-gene-listbox"
          role="listbox"
        >
          {hits.map((symbol, i) => (
            <li
              key={symbol}
              role="option"
              aria-selected={i === highlighted}
              className={
                i === highlighted ? 'msv-option highlighted' : 'msv-option'
              }
              onMouseEnter={() => {
                setHighlighted(i)
              }}
              onMouseDown={e => {
                // mousedown, not click: the document listener above closes the
                // list on mousedown and the click would never arrive
                e.preventDefault()
                choose(symbol)
              }}
            >
              {symbol}
            </li>
          ))}
        </ul>
      )}
    </div>
  )
}

// Which alignment the page shows and the session carries.
type AlignSource = 'live' | 'hundredWay'

interface LoadedAlignment {
  inline?: InlineMsa
  indexed?: IndexedMsa
  // what the embedded viewer renders
  fasta: string
  newick?: string
  treeUri?: string
  gff?: string
  rowCount: number
  // for the 100-way, the knownCanonical model the alignment was built from —
  // swapped into the session so genome, alignment and structure share codons
  structureOverrides?: Partial<GeneStructure>
}

// Everything downstream of a resolved gene. The page is a launcher, so the
// session card leads with the one primary action and the two heavy views — the
// domain cartoon and the alignment — fold away underneath it. The alignment
// still loads while its disclosure is closed, because it is what the launched
// session carries.
function GeneResults({
  structure,
  panel,
  panelError,
  precomputed,
  hundredWay,
  taxId,
  status,
  onProgress,
}: Resolved & {
  taxId: number
  status: string
  onProgress: (s: string) => void
}) {
  const { symbol } = structure
  const [collapse, setCollapse] = useState(true)
  const [flip, setFlip] = useState(structure.transcript.strand === -1)
  // The 100-way is one indexed read, so where it exists it is the better first
  // impression: 100 vertebrates with no wait, against a Clustal Omega job. The
  // live panel keeps the domain overlay, which is why both are offered.
  const [source, setSource] = useState<AlignSource>(
    hundredWay ? 'hundredWay' : 'live',
  )
  // The live alignment is the only one worth gating behind a click — it costs an
  // EBI job. The 100-way loads as soon as it is chosen.
  const [wantLive, setWantLive] = useState(false)
  const wantAlignment = source === 'hundredWay' || wantLive

  const {
    data: alignment,
    error,
    isLoading: aligning,
  } = useSWRImmutable(
    wantAlignment
      ? (['protein-alignment', symbol, taxId, source] as const)
      : null,
    ([, sym, , src]) =>
      src === 'hundredWay'
        ? loadHundredWay(sym)
        : loadLive(panel!, precomputed, onProgress),
    LIVE_QUERY,
  )

  return (
    <>
      <LaunchCard
        structure={structure}
        alignment={alignment}
        collapse={collapse}
        onToggleCollapse={setCollapse}
        flip={flip}
        onToggleFlip={setFlip}
      />

      {panelError && (
        <p className="ui-note">
          No ortholog panel for {symbol}: {panelError}
        </p>
      )}
      {panel && <DomainSection panel={panel} />}

      {(hundredWay || panel) && (
        <AlignmentSection
          gene={symbol}
          alignment={alignment}
          error={error}
          aligning={aligning}
          status={status}
          source={source}
          onSource={setSource}
          bothSources={hundredWay && !!panel}
          panelRows={panel?.rows.length ?? 0}
          precomputed={!!precomputed}
          wantLive={wantLive}
          onBuildLive={() => {
            setWantLive(true)
          }}
        />
      )}

      <p className="ui-hint">
        <a href={geneUrl('/orthologs', symbol, taxId)}>Ortholog table</a> ·{' '}
        <a href={geneUrl('/conserved-gene-order', symbol, taxId)}>
          Conserved gene order
        </a>
      </p>
    </>
  )
}

// The cartoon, and the species it could not cover. Folded away because it
// answers a question the reader has after the launch rather than before it.
function DomainSection({ panel }: { panel: ProteinPanel }) {
  const found = new Set(panel.rows.map(r => r.taxId))
  // Which model species came back empty is worth saying only when the model
  // species are what the panel asked for. A broad panel takes NCBI's ortholog
  // order instead, so naming the four it never requested reads as a gap.
  const curated = panel.rows.length <= COMMON_SPECIES.length
  const missing = curated ? COMMON_SPECIES.filter(s => !found.has(s.taxId)) : []
  return (
    <details className="ui-disclosure">
      <summary>
        Domain architecture{' '}
        <span className="ui-caption">
          {panel.rows.length} species
          {curated ? ` of ${COMMON_SPECIES.length}` : ''}
        </span>
      </summary>
      <ProteinDomainCartoon rows={panel.rows} />
      {missing.length > 0 && (
        <p className="ui-note">
          No ortholog in {missing.map(s => s.label).join(', ')}
        </p>
      )}
    </details>
  )
}

// The alignment, folded the same way. `open` is controlled because the viewer
// may only mount once the disclosure is: react-msaview sizes its canvas from the
// container it first mounts into, and a closed <details> is display: none.
function AlignmentSection({
  gene,
  alignment,
  error,
  aligning,
  status,
  source,
  onSource,
  bothSources,
  panelRows,
  precomputed,
  wantLive,
  onBuildLive,
}: {
  gene: string
  alignment: LoadedAlignment | undefined
  error: unknown
  aligning: boolean
  status: string
  source: AlignSource
  onSource: (s: AlignSource) => void
  bothSources: boolean
  // rows the live panel would align, which is not COMMON_SPECIES.length once a
  // precomputed broad panel is in play
  panelRows: number
  precomputed: boolean
  wantLive: boolean
  onBuildLive: () => void
}) {
  const [open, setOpen] = useState(false)
  // Offering to build only means something on the live arm, and only while it
  // has not already been asked for: `wantLive` is not in the SWR key, so a
  // second click refetches nothing. The 100-way arm loads on selection, so when
  // it fails the honest answer is the error alone — a build button there is
  // inert, and the fetcher behind it would dereference an absent panel.
  const canBuild = source === 'live' && panelRows > 0 && !wantLive
  return (
    <details
      className="ui-disclosure"
      open={open}
      onToggle={e => {
        setOpen(e.currentTarget.open)
      }}
    >
      <summary>
        Residue alignment{' '}
        <span className="ui-caption">
          {alignment
            ? `${alignment.rowCount} rows`
            : source === 'hundredWay'
              ? '100 vertebrates'
              : `${panelRows} species`}
        </span>
      </summary>

      {bothSources && (
        <AlignmentSourceChoice
          source={source}
          panelRows={panelRows}
          precomputed={precomputed}
          onChange={onSource}
        />
      )}
      <ErrorMessage
        error={error}
        className="ui-error"
      />

      {open && alignment ? (
        <AlignmentPanel
          alignment={alignment}
          gene={gene}
        />
      ) : aligning ? (
        <p className="ui-hint">{status || 'Aligning…'}</p>
      ) : alignment || !canBuild ? null : (
        <div className="msv-advanced">
          <button
            className="ui-btn-secondary"
            onClick={onBuildLive}
          >
            Build cross-species alignment
          </button>
          <span className="ui-caption">
            {precomputed
              ? 'precomputed'
              : `EBI Clustal Omega on ${panelRows} proteins`}
          </span>
        </div>
      )}
    </details>
  )
}

// The embedded viewer. An alignment is the one thing on this page that cannot
// live inside the article's measure — it is a hundred rows of a wide matrix, and
// at 60rem you read a sliver of it — so inline it breaks out to the window width
// (see .msv-align in the page styles), and Expand hands it the whole viewport.
//
// MSAViewer builds its MST model once, from the props it first mounts with, so
// changing the height means a new instance: `key` makes the remount deliberate
// rather than something React decides. It costs nothing here — both alignments
// are already strings in memory, so nothing is re-fetched — but it does reset
// scroll position, which is the trade for not reaching into the model.
function AlignmentPanel({
  alignment,
  gene,
}: {
  alignment: LoadedAlignment
  gene: string
}) {
  const [expanded, setExpanded] = useState(false)
  const height = useViewportHeight(expanded)

  const viewer = (
    <Suspense fallback={<p className="ui-hint">Loading alignment viewer…</p>}>
      <MSAViewer
        key={expanded ? 'expanded' : 'inline'}
        msa={alignment.fasta}
        {...(alignment.newick ? { tree: alignment.newick } : {})}
        {...(alignment.treeUri
          ? {
              treeFilehandle: {
                uri: alignment.treeUri,
                locationType: 'UriLocation',
              },
            }
          : {})}
        {...(alignment.gff ? { gff: alignment.gff } : {})}
        colorScheme="clustalx_protein_dynamic"
        treeAreaWidth={200}
        height={height}
      />
    </Suspense>
  )

  const toolbar = (
    <div className="msv-align-bar">
      <span className="msv-align-title">
        {gene} · {alignment.rowCount} rows
      </span>
      <button
        className="ui-btn-secondary"
        onClick={() => {
          setExpanded(!expanded)
        }}
      >
        {expanded ? 'Close' : 'Expand ⤢'}
      </button>
    </div>
  )

  if (expanded) {
    return (
      <dialog
        className="msv-align-dialog"
        ref={el => {
          // showModal() throws if the dialog is already open, which a StrictMode
          // ref re-attach would do
          if (el && !el.open) {
            el.showModal()
          }
        }}
        onClose={() => {
          setExpanded(false)
        }}
      >
        {toolbar}
        {viewer}
      </dialog>
    )
  }
  return (
    <div className="msv-align">
      {toolbar}
      {viewer}
    </div>
  )
}

// Pixel height for the viewer, which takes a number rather than a CSS length.
// Expanded fills the viewport bar the dialog's own chrome; inline is a fixed
// panel. Tracks resize so a rotated phone or a dragged window does not leave the
// canvas the wrong size.
const INLINE_HEIGHT = 520

function useViewportHeight(expanded: boolean) {
  const [viewport, setViewport] = useState(() =>
    typeof window === 'undefined' ? 900 : window.innerHeight,
  )
  useEffect(() => {
    const onResize = () => {
      setViewport(window.innerHeight)
    }
    window.addEventListener('resize', onResize)
    return () => {
      window.removeEventListener('resize', onResize)
    }
  }, [])
  return expanded ? Math.max(360, viewport - 120) : INLINE_HEIGHT
}

// The hosted 100-way for one gene: the alignment block, and the transcript it
// was built from so the session's connectedFeature shares its codon ordinals.
async function loadHundredWay(symbol: string): Promise<LoadedAlignment> {
  const [msa, transcript] = await Promise.all([
    fetchHundredWayAlignment(symbol),
    fetchHundredWayTranscript(symbol),
  ])
  if (!msa) {
    throw new Error(`No 100-way alignment row for ${symbol}`)
  }
  return {
    indexed: {
      msaUri: HUNDRED_WAY_MSA,
      treeUri: HUNDRED_WAY_TREE,
      msaName: symbol,
      querySeqName: msa.querySeqName,
    },
    fasta: msa.fasta,
    treeUri: HUNDRED_WAY_TREE,
    rowCount: msa.rowCount,
    structureOverrides: {
      // the aligned hg38 row is the knownCanonical translation, so it is the
      // protein whose residues the alignment's columns count
      proteinSequence: msa.querySequence,
      ...(transcript ? { transcript } : {}),
    },
  }
}

// The live panel aligned at EBI, with the CDD domains as a per-row overlay.
async function loadLive(
  panel: ProteinPanel,
  precomputed: ProteinAlignment | undefined,
  onProgress: (s: string) => void,
): Promise<LoadedAlignment> {
  const aligned =
    precomputed ?? (await alignProteinPanel(panel, { onProgress }))
  const queryRow =
    panel.rows.find(r => r.taxId === panel.query.refTaxonId) ?? panel.rows[0]!
  return {
    inline: {
      fasta: aligned.fasta,
      newick: aligned.newick,
      gff: aligned.gff,
      querySeqName: queryRow.label,
    },
    fasta: aligned.fasta,
    newick: aligned.newick,
    gff: aligned.gff,
    rowCount: (aligned.fasta.match(/^>/gm) ?? []).length,
  }
}

// The choice between the two alignment sources, rendered by AlignmentSection
// only where there is a choice to make. Each option says what it costs and what
// it gives up.
function AlignmentSourceChoice({
  source,
  panelRows,
  precomputed,
  onChange,
}: {
  source: AlignSource
  panelRows: number
  precomputed: boolean
  onChange: (s: AlignSource) => void
}) {
  return (
    <div className="msv-source">
      <span className="msv-source-label">Alignment</span>
      <label className="msv-source-option">
        <input
          type="radio"
          name="align-source"
          checked={source === 'hundredWay'}
          onChange={() => {
            onChange('hundredWay')
          }}
        />
        100 vertebrates <span className="ui-caption">instant, no domains</span>
      </label>
      <label className="msv-source-option">
        <input
          type="radio"
          name="align-source"
          checked={source === 'live'}
          onChange={() => {
            onChange('live')
          }}
        />
        {panelRows} species{' '}
        <span className="ui-caption">
          domains{precomputed ? ', precomputed' : ', built at EBI'}
        </span>
      </label>
    </div>
  )
}

// Joins a short list into prose: "a", "a and b", "a, b and c".
function joinList(parts: string[]) {
  return parts.length > 1
    ? `${parts.slice(0, -1).join(', ')} and ${parts.at(-1)}`
    : (parts[0] ?? '')
}

// The launch, and what the page is for — so it leads, and carries one primary
// action. What used to be a row of chips is now either a fact in the meta line
// or part of the sentence saying what the session opens with.
function LaunchCard({
  structure,
  alignment,
  collapse,
  onToggleCollapse,
  flip,
  onToggleFlip,
}: {
  structure: GeneStructure
  alignment: LoadedAlignment | undefined
  collapse: boolean
  onToggleCollapse: (v: boolean) => void
  flip: boolean
  onToggleFlip: (v: boolean) => void
}) {
  const [detailsOpen, setDetailsOpen] = useState(false)
  // The 100-way carries its own transcript and query protein; swapping them in
  // here is what keeps the launched session's three views on one coordinate
  // space, rather than pairing that alignment with a different isoform.
  const launched = { ...structure, ...alignment?.structureOverrides }
  const { transcript, assemblyAccession, uniprotId } = launched
  const { codingBp } = geneStats(transcript)
  const { session, url } = buildSessionUrl({
    structure: launched,
    collapse,
    flip,
    inlineMsa: alignment?.inline,
    indexedMsa: alignment?.indexed,
  })
  const carries = [
    collapse ? 'the coding exons back to back' : 'the gene in its genome',
    uniprotId ? 'the AlphaFold structure' : undefined,
    alignment ? `a ${alignment.rowCount}-row alignment` : undefined,
  ].filter((c): c is string => !!c)

  return (
    <div className="msv-result">
      <h2>
        {transcript.geneName} <span className="msv-sub">{transcript.name}</span>
      </h2>
      <p className="msv-meta">
        {assemblyAccession} · {launched.target.assemblyName} ·{' '}
        {launched.target.canonicalRefName(transcript.refName)}{' '}
        {transcript.strand === 1 ? '+' : '−'} · {transcript.cds.length} coding
        exons · {codingBp.toLocaleString()} bp CDS
      </p>

      <div className="msv-actions">
        <a
          className="msv-open"
          href={url}
          target="_blank"
          rel="noopener noreferrer"
        >
          Open in JBrowse ↗
        </a>
        <label className="msv-collapse">
          <input
            type="checkbox"
            checked={collapse}
            onChange={e => {
              onToggleCollapse(e.target.checked)
            }}
          />
          Collapse introns
        </label>
        {transcript.strand === -1 && (
          <label className="msv-collapse">
            <input
              type="checkbox"
              checked={flip}
              onChange={e => {
                onToggleFlip(e.target.checked)
              }}
            />
            Read 5′→3′
          </label>
        )}
        <button
          className="ui-linkbtn"
          onClick={() => {
            setDetailsOpen(true)
          }}
        >
          Session details
        </button>
      </div>
      <p className="ui-caption">
        Opens {joinList(carries)} in one connected session.
      </p>

      {detailsOpen && (
        <SessionDetailsDialog
          onClose={() => {
            setDetailsOpen(false)
          }}
          transcript={transcript}
          session={session}
          collapse={collapse}
          flip={flip}
          uniprotId={uniprotId}
        />
      )}
    </div>
  )
}
