// Precomputed panel + alignment for the example genes (generated by
// generateBroadPanel.ts), keyed by cacheKey(). Lets a chip click render the
// cartoon and the full alignment with no NCBI/EBI wait.
//
// The alignment half stays optional in the type because the generator's survey
// mode (no --align) writes the panel alone. What the shipped file actually holds
// is the other arrangement: every entry has its alignment, and none of them has
// sequences — see `usable`. A chip with no entry here is not a broken chip: it
// resolves live, on the same defaults the generator used.
interface CachedExample {
  panel: ProteinPanel
  alignment?: ProteinAlignment
}

// Optional precomputed cache: a load failure just means examples resolve live,
// so degrade to an empty map rather than surfacing an error.
function loadExampleCache(): Promise<Record<string, CachedExample>> {
  return loadJsonOnce<Record<string, CachedExample>>(
    '/proteinExamples.json',
  ).catch((): Record<string, CachedExample> => ({}))
}

// An entry that shipped its alignment has had the sequences stripped out from
// under it. An entry with neither is the one shape that cannot serve: it would
// draw the cartoon and then fail the alignment on a precondition the reader can
// do nothing about, so it is ignored rather than trusted.
function usable(entry: CachedExample | undefined) {
  return entry && (entry.alignment || canAlign(entry.panel)) ? entry : undefined
}

// client:only island, so window is available for the shareable link.
function paramsFromUrl() {
  const p = new URLSearchParams(window.location.search)
  const ref = Number(p.get('ref'))
  const known = COMMON_SPECIES.some(s => s.taxId === ref)
  return {
    gene: p.get('gene')?.trim() ?? '',
    ref: known ? ref : 9606,
    focus: focusFromParams(p),
  }
}

// The same shape written onto the page, so what is on screen stays a link:
// the gene, the species, and what the session opens on.
function syncProteinUrl(
  symbol: string,
  taxId: number,
  focus: ExampleFocus | undefined,
) {
  const p = new URLSearchParams({ gene: symbol, ref: String(taxId) })
  focusToParams(focus, p)
  window.history.replaceState(null, '', `?${p}`)
}

function speciesLabel(taxId: number) {
  return COMMON_SPECIES.find(s => s.taxId === taxId)?.label ?? `taxon ${taxId}`
}

// A progress line belongs to one query. The resolvers post through a callback
// that outlives the gene it was created for — a slow ortholog fetch keeps
// reporting after the reader has moved on — so every message names its query
// and the page shows only the current one's.
interface Progress {
  key: string
  message: string
}

const queryKey = (gene: string, ref: number) => `${gene}:${ref}`

// What following the ortholog into another species came to. `none` clears the
// results, since they belong to the species the select no longer shows; an
// error puts the select back where the results are and offers a retry.
interface Follow {
  ref: number
  symbol: string
  outcome: 'pending' | 'none' | Error
}

type PanelOutcome = { panel: ProteinPanel } | { panelError: string }

interface Resolved {
  structure: GeneStructure
  panel: PanelOutcome
  // the precomputed alignment for an example gene, used to skip EBI
  precomputed?: ProteinAlignment
  // whether this gene has a row in the hosted 100-way alignment
  hundredWay: boolean
}

// Phase 1: the gene's own genome/structure, then the ortholog domain panel.
// Example genes take the panel side from the precomputed cache instantly;
// everything else resolves live.
//
// The structure comes FIRST so its resolved GeneID can seed the panel: ncbiFetch
// serializes every request, so running them concurrently would not overlap them
// anyway, and the structure's id is the gene NCBI actually places on an
// assembly. The example cache and the 100-way index are not NCBI reads, so they
// do overlap.
//
// A failed panel is NOT fatal. The genome view and the structure come from the
// structure half alone, and they are worth having even when no ortholog set
// covers the gene — which is exactly the case on the species where ortholog
// coverage is thinnest.
async function resolveGene(
  sym: string,
  ref: number,
  onProgress: (s: string) => void,
): Promise<Resolved> {
  const cachePending = loadExampleCache()
  const structure = await fetchGeneStructure(sym, ref)
  const cached = usable((await cachePending)[cacheKey(sym, ref)])
  // keyed on NCBI's canonical spelling of the symbol, which is what the hosted
  // index uses — a typed "tp53" would otherwise miss; the panel is built on the
  // same spelling, so its query row is labelled the way NCBI labels the gene
  const hundredWayPending = hasHundredWay(structure.symbol, ref)
  const panel = await (
    cached
      ? Promise.resolve(cached.panel)
      : assembleProteinPanel(structure.symbol, ref, {
          onProgress,
          geneId: structure.geneId,
        })
  ).then(
    (panel): PanelOutcome => ({ panel }),
    (e: unknown): PanelOutcome => ({ panelError: errorText(e) }),
  )
  return {
    structure,
    panel,
    precomputed: cached?.alignment,
    hundredWay: await hundredWayPending,
  }
}

export default function ProteinBrowser() {
  // The submitted query, as opposed to what is currently in the boxes: it is the
  // SWR key, so it changes only on Explore/Enter/an example chip. Seeded from the
  // page url, which is what makes a shared ?gene=&ref= link resolve on mount —
  // this island is client:only, so window is readable during the first render.
  const [arrival] = useState(paramsFromUrl)
  const [query, setQuery] = useState({ gene: arrival.gene, ref: arrival.ref })
  const [gene, setGene] = useState(query.gene)
  const [taxId, setTaxId] = useState(query.ref)
  const [progress, setProgress] = useState<Progress>()
  const [follow, setFollow] = useState<Follow>()
  const [helpOpen, setHelpOpen] = useState(false)
  // The chip the current query came from, when it did: its focus and story
  // are applied to the results. A typed query has none; a link that names a
  // chip's gene and focus is that chip.
  const [example, setExample] = useState(() =>
    exampleMatching(arrival.ref, arrival.gene, arrival.focus),
  )
  // Counts submissions, so resubmitting the gene on screen (its chip again,
  // say) starts its results over with what the url now says. The arrival is
  // submission 0, the only one the link's own focus applies to.
  const [submission, setSubmission] = useState(0)
  // Which species switch is the latest, so a slower earlier lookup cannot land
  // on top of it. A new query supersedes a pending switch the same way.
  const followToken = useRef(0)

  const {
    data,
    error,
    isLoading: loading,
    mutate: retry,
  } = useSWRImmutable(
    query.gene ? (['protein-gene', query.gene, query.ref] as const) : null,
    ([, sym, ref]) =>
      resolveGene(sym, ref, message => {
        setProgress({ key: queryKey(sym, ref), message })
      }),
    LIVE_QUERY,
  )
  const status =
    progress?.key === queryKey(query.gene, query.ref) ? progress.message : ''

  // Submits a query. The same query again is a no-op for SWR — an equal key is
  // not a refetch — so a failed one is re-run explicitly.
  const run = (rawQuery: string, ref: number, chip?: ProteinExample) => {
    const sym = rawQuery.trim()
    if (sym) {
      followToken.current += 1
      setFollow(undefined)
      setExample(chip)
      setSubmission(n => n + 1)
      setGene(sym)
      setTaxId(ref)
      if (sym === query.gene && ref === query.ref) {
        if (error) {
          void retry()
        }
      } else {
        setQuery({ gene: sym, ref })
      }
      syncProteinUrl(sym, ref, chip?.focus)
    }
  }

  // Symbols do not carry across organisms, so a species switch follows NCBI's
  // ortholog to the new species rather than re-running a symbol that means
  // nothing there. With nothing resolved to follow it just changes the
  // species, and drops a gene still resolving in the old one.
  const switchSpecies = (ref: number) => {
    setTaxId(ref)
    followToken.current += 1
    const token = followToken.current
    const structure = data?.structure
    if (structure && query.gene) {
      const { symbol, geneId } = structure
      setFollow({ ref, symbol, outcome: 'pending' })
      resolveOrthologSymbol(geneId, ref).then(
        found => {
          if (token === followToken.current) {
            if (found) {
              run(found, ref)
            } else {
              setFollow({ ref, symbol, outcome: 'none' })
              setGene('')
              setQuery({ gene: '', ref })
              syncProteinUrl('', ref, undefined)
            }
          }
        },
        (e: unknown) => {
          if (token === followToken.current) {
            setFollow({
              ref,
              symbol,
              outcome: e instanceof Error ? e : new Error(String(e)),
            })
            setTaxId(query.ref)
          }
        },
      )
    } else {
      setFollow(undefined)
      if (query.gene) {
        setQuery({ gene: '', ref })
        syncProteinUrl('', ref, undefined)
      }
    }
  }

  const examples = examplesFor(taxId)

  return (
    <div>
      <div className="ui-form">
        <GeneCombobox
          value={gene}
          taxId={taxId}
          disabled={false}
          onChange={v => {
            setGene(v)
          }}
          onSubmit={symbol => {
            run(symbol, taxId)
          }}
        />
        <select
          className="ui-select"
          value={taxId}
          onChange={e => {
            switchSpecies(Number(e.target.value))
          }}
          aria-label="Reference organism"
        >
          {COMMON_SPECIES.map(s => (
            <option
              key={s.taxId}
              value={s.taxId}
            >
              {s.label}
            </option>
          ))}
        </select>
        <button
          className="ui-btn"
          onClick={() => {
            run(gene, taxId)
          }}
          disabled={!gene.trim()}
        >
          Explore
        </button>
        <HelpButton
          label="How the protein browser works"
          onClick={() => {
            setHelpOpen(true)
          }}
        />
      </div>

      <div className="msv-examples">
        <span>Examples:</span>
        {examples.map(ex => (
          <button
            key={ex.symbol}
            className="ui-chip-btn"
            title={ex.note}
            onClick={() => {
              run(ex.symbol, taxId, ex)
            }}
          >
            {ex.symbol}
          </button>
        ))}
      </div>

      {follow?.outcome === 'pending' && (
        <p className="ui-hint">
          Following {follow.symbol} into {speciesLabel(follow.ref)}…
        </p>
      )}
      {follow?.outcome === 'none' && (
        <p className="ui-note">
          NCBI lists no {speciesLabel(follow.ref)} ortholog of {follow.symbol}.
          Type a {speciesLabel(follow.ref)} gene or pick an example.
        </p>
      )}
      {follow && follow.outcome instanceof Error && (
        <p className="ui-error">
          Could not follow {follow.symbol} into {speciesLabel(follow.ref)}:{' '}
          {errorText(follow.outcome)}{' '}
          <button
            className="ui-linkbtn"
            onClick={() => {
              switchSpecies(follow.ref)
            }}
          >
            Try again
          </button>
        </p>
      )}

      {loading && <p className="ui-hint">{status || 'Resolving…'}</p>}
      {!loading && error ? (
        <p className="ui-error">
          {errorText(error)}{' '}
          <button
            className="ui-linkbtn"
            onClick={() => {
              void retry()
            }}
          >
            Try again
          </button>
        </p>
      ) : null}

      {data && (
        // Remounted per submission, which is what drops a previous gene's
        // alignment request, superposition picks and focus without an effect.
        <GeneResults
          key={`${query.gene}:${query.ref}:${submission}`}
          {...data}
          taxId={query.ref}
          status={status}
          example={
            example?.symbol.toUpperCase() === query.gene.toUpperCase()
              ? example
              : undefined
          }
          linkFocus={submission === 0 ? arrival.focus : undefined}
          onProgress={message => {
            setProgress({ key: queryKey(query.gene, query.ref), message })
          }}
        />
      )}

      {helpOpen && (
        <HelpDialog
          onClose={() => {
            setHelpOpen(false)
          }}
        />
      )}
    </div>
  )
}

// The canonical sequence — the coordinate space the map's regions are on. The
// canonical AlphaFold model is folded from exactly it; failing that, the
// translation, which is the canonical for most genes.
function canonicalSequence(structure: GeneStructure) {
  return (
    structure.alphafold.find(m => !m.accession.includes('-'))?.sequence ??
    structure.proteinSequence
  )
}

// A CDD domain off the ortholog cartoon as a focus. Its coordinates are on the
// panel's query protein rather than the canonical, which the card allows for;
// no accession is what marks it as such.
function cartoonFocus(d: Domain): Focus {
  return {
    kind: 'region',
    region: { kind: 'domain', name: d.name, start: d.start, end: d.end },
  }
}

// Everything downstream of a resolved gene. The page is a launcher, so the
// session card leads with the one primary action; the protein map under it is
// where the session's focus is chosen, and the two heavy views — the ortholog
// cartoon and the alignment — fold away beneath. The alignment still loads
// while its disclosure is closed, because it is what the launched session
// carries.
function GeneResults({
  structure,
  panel: panelOutcome,
  precomputed,
  hundredWay,
  taxId,
  status,
  onProgress,
  example,
  linkFocus,
}: Resolved & {
  taxId: number
  status: string
  onProgress: (s: string) => void
  example?: ProteinExample
  // what the link the reader arrived by named, when it was not a chip's
  linkFocus?: ExampleFocus
}) {
  const { symbol, uniprotId } = structure
  const canonical = canonicalSequence(structure)
  const panel = 'panel' in panelOutcome ? panelOutcome.panel : undefined
  const preset = example?.focus ?? linkFocus

  // The map's regions: InterPro's, on the query protein alone, so they are on
  // screen in a second or two. The partner list is PDBe's and can run to half a
  // megabyte on a well-studied protein, so it is read when asked for — or when
  // the chip's preset names a partner.
  const {
    data: regions,
    error: regionsError,
    isLoading: regionsLoading,
  } = useSWRImmutable(
    uniprotId ? (['interpro-regions', uniprotId] as const) : null,
    ([, id]) => fetchInterProRegions(id),
    LIVE_QUERY,
  )
  const [wantPartners, setWantPartners] = useState(!!preset?.partner)
  const {
    data: partners,
    error: partnersError,
    isLoading: partnersLoading,
    mutate: retryPartners,
  } = useSWRImmutable(
    uniprotId && wantPartners
      ? (['pdbe-interfaces', uniprotId] as const)
      : null,
    ([, id]) => fetchInterfaceRegions(id),
    LIVE_QUERY,
  )
  const partnersState: PartnersState = !wantPartners
    ? { status: 'idle' }
    : partnersLoading
      ? { status: 'loading' }
      : partnersError
        ? { status: 'error', message: errorText(partnersError) }
        : { status: 'loaded', partners: partners ?? [] }

  // What the session opens on. The chip's preset holds until the reader picks
  // something else; `null` records that they cleared it, so it does not come
  // back when the regions it named finish loading.
  const [focusChoice, setFocusChoice] = useState<Focus | null>()
  const focus =
    focusChoice === null
      ? undefined
      : (focusChoice ?? focusFromPreset(preset, regions, partners))
  const setFocus = (next: Focus | undefined) => {
    setFocusChoice(next ?? null)
    syncProteinUrl(symbol, taxId, presetOf(next))
  }
  const family = focusFamily(focus, regions ?? [])

  // The alignment offered first is the one the reader's last gesture asks for.
  // A focused domain asks what the domain looks like across life, and that is
  // its family's seed. Otherwise the 100-way is one indexed read, so where it
  // exists it is the better first impression: 100 vertebrates with no wait,
  // against a Clustal Omega job. Elsewhere the UniRef cluster leads, because it
  // costs no job either and exists for any gene UniProt knows. The live panel
  // keeps the domain overlay, which is why it stays offered; phmmer is the
  // reach into remote homologs. An explicit pick holds while it is on offer.
  const sources: AlignSource[] = [
    ...(family ? ['pfam' as const] : []),
    ...(hundredWay ? ['hundredWay' as const] : []),
    'uniref',
    ...(panel ? ['live' as const] : []),
    'phmmer',
  ]
  const [sourceChoice, setSourceChoice] = useState<AlignSource>()
  const source =
    sourceChoice && sources.includes(sourceChoice) ? sourceChoice : sources[0]!
  // The live alignment is the only one worth gating behind a click — it costs an
  // EBI job here on the page. The others load as soon as they are chosen: the
  // 100-way is one read, the seed is three, and the built sources are requests
  // the session carries. A residue or a preset family waits for InterPro to
  // say which seed it opens, rather than loading the 100-way to discard it.
  const [wantLive, setWantLive] = useState(false)
  const familyPending =
    regionsLoading &&
    (focus?.kind === 'residue' || (focusChoice === undefined && !!preset?.pfam))
  const wantAlignment = !familyPending && (source !== 'live' || wantLive)
  // Swiss-Prot accessions of the ortholog rows marked for superposition.
  const [superposed, setSuperposed] = useState<string[]>([])
  // Each alignment fetch abandons the EBI job before it, and unmounting — this
  // component is remounted per submission — abandons the last. The one effect
  // here, because a job at another server is exactly the external system an
  // effect is for.
  const [jobs] = useState(latestJob)
  useEffect(
    () => () => {
      jobs.stop()
    },
    [jobs],
  )

  // Only the seed alignment is keyed on the domain instance and the residue it
  // marks, since both are baked into its placed rows. Keying the others on
  // them too would submit a fresh EBI job for every residue typed.
  const residueFocus = focus?.kind === 'residue' ? focus.position : 0
  const {
    data: alignment,
    error,
    isLoading: aligning,
    mutate: retry,
  } = useSWRImmutable(
    wantAlignment
      ? ([
          'protein-alignment',
          symbol,
          taxId,
          source,
          ...(source === 'pfam'
            ? [family?.pfam ?? '', family?.start ?? 0, residueFocus]
            : []),
        ] as const)
      : null,
    ([, sym, , src]) => {
      const signal = jobs.next()
      switch (src) {
        case 'hundredWay':
          return loadHundredWay(sym)
        case 'live':
          return loadLive(structure, panel!, precomputed, onProgress, signal)
        case 'pfam':
          return family
            ? loadPfam(structure, family, focus)
            : Promise.reject(new Error('No domain family in focus'))
        default:
          return Promise.resolve(loadBuilt(src, structure))
      }
    },
    LIVE_QUERY,
  )

  const toggleSuperpose = (uniprot: string) => {
    setSuperposed(
      superposed.includes(uniprot)
        ? superposed.filter(u => u !== uniprot)
        : [...superposed, uniprot],
    )
  }

  return (
    <>
      <ProteinLaunchCard
        structure={structure}
        alignment={alignment}
        aligning={aligning || familyPending}
        superposed={
          panel
            ? panel.rows.filter(
                r => r.uniprot && superposed.includes(r.uniprot),
              )
            : []
        }
        onRemoveSuperposed={u => {
          toggleSuperpose(u)
        }}
        queryRow={panel?.rows.find(r => r.taxId === panel.query.refTaxonId)}
        focus={focus}
        onClearFocus={() => {
          setFocus(undefined)
        }}
        story={example?.story}
      />

      {uniprotId && (
        <section className="pm-section">
          <h3 className="pm-title">
            Protein map{' '}
            <span className="ui-caption">
              {uniprotId} · InterPro domains, PDBe interfaces
            </span>
          </h3>
          {regionsLoading && <p className="ui-hint">Reading InterPro…</p>}
          {regionsError ? (
            <p className="ui-note">
              No InterPro annotation could be read: {errorText(regionsError)}
            </p>
          ) : null}
          {regions && (
            <ProteinMap
              length={
                canonical?.length ?? Math.max(0, ...regions.map(r => r.end))
              }
              sequence={canonical}
              regions={regions}
              partners={partnersState}
              onLoadPartners={() => {
                if (wantPartners) {
                  void retryPartners()
                } else {
                  setWantPartners(true)
                }
              }}
              focus={focus}
              onFocus={setFocus}
            />
          )}
          <p className="ui-caption">
            Click a domain, a site or a partner and the session opens on it: lit
            in all three views, and for a domain with a Pfam family, with that
            family&rsquo;s seed as the alignment. A partner opens the complex
            PDBe saw the two in, instead of the monomer.
          </p>
        </section>
      )}

      {'panelError' in panelOutcome && (
        <p className="ui-note">
          No ortholog panel for {symbol}: {panelOutcome.panelError}
        </p>
      )}
      {panel && (
        <DomainSection
          panel={panel}
          selectedDomain={
            focus?.kind === 'region' && !focus.region.accession
              ? focus.region
              : undefined
          }
          onSelectDomain={d => {
            const next = cartoonFocus(d)
            setFocus(sameFocus(focus, next) ? undefined : next)
          }}
          superposed={superposed}
          onToggleSuperpose={u => {
            toggleSuperpose(u)
          }}
        />
      )}

      <ProteinAlignmentSection
        gene={symbol}
        alignment={alignment}
        error={error}
        aligning={aligning || familyPending}
        status={familyPending ? 'Asking InterPro which domain family…' : status}
        source={source}
        sources={sources}
        onSource={s => {
          setSourceChoice(s)
        }}
        panelRows={panel ? alignedRows(panel).length : 0}
        precomputed={!!precomputed}
        family={family}
        wantLive={wantLive}
        onBuildLive={() => {
          setWantLive(true)
        }}
        onRetry={() => {
          void retry()
        }}
      />

      <p className="ui-hint">
        <a href={geneUrl('/gene/', symbol, taxId)}>
          {symbol} gene page — orthologs and conserved gene order →
        </a>
      </p>
    </>
  )
}

// The cartoon, and the species it could not cover. Folded away because it
// answers a question the reader has after the launch rather than before it.
function DomainSection({
  panel,
  selectedDomain,
  onSelectDomain,
  superposed,
  onToggleSuperpose,
}: {
  panel: ProteinPanel
  selectedDomain: Domain | undefined
  onSelectDomain: (d: Domain) => void
  superposed: string[]
  onToggleSuperpose: (uniprot: string) => void
}) {
  const found = new Set(panel.rows.map(r => r.taxId))
  // The panel asks its source for every species it has, so a model organism
  // absent from a short panel really has no ortholog on record and is worth
  // naming. On a full panel the same list is noise — it would name the four
  // invertebrates under 60 vertebrates on nearly every gene.
  const short = panel.rows.length <= COMMON_SPECIES.length
  const missing = short ? COMMON_SPECIES.filter(s => !found.has(s.taxId)) : []
  // "60 of 658" rather than a bare 60: a capped panel should say so.
  const total = panel.query.total
  return (
    <details className="ui-disclosure">
      <summary>
        Domain architecture{' '}
        <span className="ui-caption">
          {panel.rows.length} species
          {total && total > panel.rows.length ? ` of ${total}` : ''}
        </span>
      </summary>
      <ProteinDomainCartoon
        rows={panel.rows}
        queryTaxId={panel.query.refTaxonId}
        selectedDomain={selectedDomain}
        onSelectDomain={onSelectDomain}
        superposed={superposed}
        onToggleSuperpose={onToggleSuperpose}
      />
      {missing.length > 0 && (
        <p className="ui-note">
          No ortholog in {missing.map(s => s.label).join(', ')}
        </p>
      )}
    </details>
  )
}
